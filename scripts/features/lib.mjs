// Registry
// ---------------------------------------------------------------------------

function* recordFiles(dir = FEATURES_DIR) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== "generated") yield* recordFiles(path);
    } else if (
      entry.name.endsWith(".md") &&
      path !== TEMPLATE &&
      path !== README
    ) {
      yield path;
    }
  }
}

/** Loads and validates every record + legacy leaf. Throws with all problems listed. */
export function loadRegistry() {
  const nodes = [];
  const errors = [];

  for (const file of recordFiles()) {
    const rel = relative(ROOT, file);
    try {
      const { frontMatter, body } = parseRecord(
        readFileSync(file, "utf8"),
        rel,
      );
      const schema = frontMatter.kind === "group" ? groupSchema : featureSchema;
      const node = schema.parse(frontMatter);
      const h1 = body.match(/^# (.+)$/m)?.[1];
      node.label =
        node.kind === "group" ? (node.title ?? h1 ?? node.id) : basename(file);
      node.file = rel;
      if (node.kind === "group") {
        if (basename(file) !== "_group.md")
          errors.push(`${rel}: groups must be named _group.md`);
        if (basename(dirname(file)) !== node.id)
          errors.push(
            `${rel}: folder name must equal the group id "${node.id}"`,
          );
      } else if (basename(file) !== `${node.id}.md`) {
        errors.push(`${rel}: file name must equal the id "${node.id}"`);
      }
      nodes.push(node);
    } catch (e) {
      errors.push(
        `${rel}: ${e instanceof z.ZodError ? z.prettifyError(e) : e.message}`,
      );
    }
  }

  try {
    for (const leaf of parseYamlish(readFileSync(LEGACY, "utf8")) ?? []) {
      const node = legacySchema.parse(leaf);
      node.kind = "legacy";
      node.label = node.title;
      if (node.delivery !== "dropped" && !node.rollout)
        errors.push(
          `roadmap.legacy.yaml/${node.id}: rollout is required unless dropped`,
        );
      nodes.push(node);
    }
  } catch (e) {
    errors.push(
      `roadmap.legacy.yaml: ${e instanceof z.ZodError ? z.prettifyError(e) : e.message}`,
    );
  }

  const byId = new Map();
  for (const n of nodes) {
    if (byId.has(n.id))
      errors.push(
        `duplicate id "${n.id}" (${byId.get(n.id).file ?? "legacy"} + ${n.file ?? "legacy"})`,
      );
    byId.set(n.id, n);
  }
  for (const n of nodes) {
    const parent = byId.get(n.parent);
    if (!AREAS.includes(n.parent)) {
      if (!parent)
        errors.push(
          `${n.id}: parent "${n.parent}" is neither a group id nor an area`,
        );
      else if (parent.kind !== "group")
        errors.push(`${n.id}: parent "${n.parent}" is not a group`);
      else if (n.area && parent.area !== n.area)
        errors.push(
          `${n.id}: area "${n.area}" ≠ parent group's "${parent.area}"`,
        );
    }
    if (n.kind === "feature") {
      if (
        ["ready", "in-progress", "uat"].includes(n.delivery) &&
        !(n.priority && n.owner && n.target)
      )
        errors.push(
          `${n.id}: priority/owner/target are required while delivery is ready|in-progress|uat`,
        );
      if (n.delivery === "verified" && !n.verification.human)
        errors.push(
          `${n.id}: verification.human is required for delivery: verified`,
        );
      for (const ref of [...n.dependsOn, ...n.blockedBy])
        if (!byId.has(ref))
          errors.push(`${n.id}: unknown id "${ref}" in dependsOn/blockedBy`);
    }
  }

  if (errors.length)
    throw new Error(`registry invalid:\n  ✗ ${errors.join("\n  ✗ ")}`);
  return nodes;
}

