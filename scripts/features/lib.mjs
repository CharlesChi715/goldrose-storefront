// Feature-registry engine — loads every record's front matter plus
// roadmap.legacy.yaml, validates the whole registry, and renders the roadmap
// trees into docs/features/README.md between the roadmap markers.
// Record format and lifecycle: docs/features/README.md.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";

export const ROOT = fileURLToPath(new URL("../..", import.meta.url));
export const FEATURES_DIR = join(ROOT, "docs", "features");
export const README = join(FEATURES_DIR, "README.md");
export const LEGACY = join(FEATURES_DIR, "roadmap.legacy.yaml");
const TEMPLATE = join(FEATURES_DIR, "TEMPLATE.md");

export const BEGIN_MARK =
  "<!-- roadmap:begin — generated by `npm run features:generate`; edit front matter or roadmap.legacy.yaml, then regenerate -->";
export const END_MARK = "<!-- roadmap:end -->";

const AREAS = ["frontend", "backend"];
const DELIVERY = [
  "backlog",
  "ready",
  "in-progress",
  "uat",
  "verified",
  "dropped",
];
const ROLLOUT = [
  "not-deployed",
  "local-only",
  "test-deployment",
  "dormant",
  "live",
];

// ---------------------------------------------------------------------------
// Minimal YAML-subset parser. Covers exactly what TEMPLATE.md's dialect uses:
// nested maps (2-space indent), sequences of scalars or maps, quoted strings,
// null, [] and inline arrays, comments. Anything else throws loudly — the
// registry must stay inside this dialect.
// ---------------------------------------------------------------------------

/** Parses the YAML subset used by feature front matter and the legacy file. */
export function parseYamlish(text) {
  const lines = [];
  for (const raw of text.split("\n")) {
    if (!raw.trim() || raw.trim().startsWith("#")) continue;
    lines.push(raw.replace(/\t/g, "  "));
  }
  let i = 0;
  const indentOf = (line) => line.match(/^ */)[0].length;

  function parseScalar(s) {
    s = s.trim();
    if (s.startsWith('"')) {
      const m = s.match(/^"((?:[^"\\]|\\.)*)"\s*$/);
      if (!m) throw new Error(`unterminated string: ${s}`);
      return m[1].replace(/\\(.)/g, "$1");
    }
    if (s.startsWith("'")) {
      const m = s.match(/^'([^']*)'\s*$/);
      if (!m) throw new Error(`unterminated string: ${s}`);
      return m[1];
    }
    s = s.replace(/\s+#.*$/, "").trim(); // trailing comment (unquoted values only)
    if (s === "null" || s === "~") return null;
    if (s === "[]") return [];
    if (s.startsWith("[") && s.endsWith("]"))
      return s
        .slice(1, -1)
        .split(",")
        .map((x) => parseScalar(x))
        .filter((x) => x !== "");
    if (s === "true") return true;
    if (s === "false") return false;
    if (/^-?\d+$/.test(s)) return Number(s);
    return s;
  }

  function parseSeq(indent) {
    const out = [];
    while (i < lines.length) {
      const line = lines[i];
      if (indentOf(line) !== indent || !line.trim().startsWith("- ")) break;
      const rest = line.trim().slice(2);
      if (/^[\w-]+:( |$)/.test(rest)) {
        lines[i] = " ".repeat(indent + 2) + rest; // treat "- key: v" as a map at indent+2
        out.push(parseMap(indent + 2));
      } else {
        out.push(parseScalar(rest));
        i++;
      }
    }
    return out;
  }

  function parseMap(indent) {
    const out = {};
    while (i < lines.length) {
      const line = lines[i];
      const ind = indentOf(line);
      if (ind < indent || line.trim().startsWith("- ")) break;
      if (ind > indent) throw new Error(`unexpected indent: "${line}"`);
      const m = line.trim().match(/^([\w][\w-]*):(?:[ \t]+(.*))?$/);
      if (!m) throw new Error(`cannot parse line: "${line}"`);
      i++;
      const [, key, rawVal] = m;
      if (
        rawVal === undefined ||
        rawVal.trim() === "" ||
        rawVal.trim().startsWith("#")
      ) {
        out[key] = parseBlock(indent + 2);
      } else {
        out[key] = parseScalar(rawVal);
      }
    }
    return out;
  }

  function parseBlock(indent) {
    const line = lines[i];
    if (line === undefined || indentOf(line) < indent) return null;
    return line.trim().startsWith("- ")
      ? parseSeq(indentOf(line))
      : parseMap(indentOf(line));
  }

  const value = parseBlock(0);
  if (i < lines.length) throw new Error(`trailing content: "${lines[i]}"`);
  return value;
}

/** Splits a record into { frontMatter, body }; throws when front matter is missing. */
export function parseRecord(text, file) {
  if (!text.startsWith("---\n"))
    throw new Error(`${file}: missing front matter`);
  const end = text.indexOf("\n---", 4);
  if (end === -1) throw new Error(`${file}: unterminated front matter`);
  return {
    frontMatter: parseYamlish(text.slice(4, end)),
    body: text.slice(end + 4),
  };
}

// ---------------------------------------------------------------------------
// Schemas
// ---------------------------------------------------------------------------

const humanSchema = z.object({
  by: z.string(),
  date: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
  environment: z.string(),
  evidence: z.string(),
});

const baseSchema = {
  schemaVersion: z.literal(1),
  id: z.string().regex(/^[a-z0-9]+(-[a-z0-9]+)*$/),
  parent: z.string(),
  area: z.enum(AREAS),
  order: z.number().int().nonnegative(),
  title: z.string().optional(),
  qualifier: z.string().optional(),
};

const featureSchema = z
  .object({
    ...baseSchema,
    kind: z.literal("feature"),
    delivery: z.enum(DELIVERY),
    rollout: z.enum(ROLLOUT),
    statusChangedAt: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
    priority: z.enum(["p0", "p1", "p2"]).optional(),
    owner: z.string().optional(),
    target: z.string().optional(),
    dependsOn: z.array(z.string()).default([]),
    blockedBy: z.array(z.string()).default([]),
    verification: z.object({
      automated: z
        .array(z.string())
        .nullable()
        .transform((v) => v ?? []),
      human: humanSchema.nullable(),
    }),
    tracking: z.unknown().optional(),
  })
  .strict();

const groupSchema = z
  .object({ ...baseSchema, kind: z.literal("group") })
  .strict();

const legacySchema = z
  .object({
    id: baseSchema.id,
    title: z.string(),
    parent: z.string(),
    order: z.number().int().nonnegative(),
    delivery: z.enum(DELIVERY),
    rollout: z.enum(ROLLOUT).optional(), // optional only when delivery is dropped
    qualifier: z.string().optional(),
  })
  .strict();

