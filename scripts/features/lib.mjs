// Rendering
// ---------------------------------------------------------------------------

const METER = {
  backlog: "○○○○ BACKLOG",
  ready: "●○○○ READY",
  "in-progress": "●●○○ IN PROGRESS",
  uat: "●●●○ UAT",
  verified: "●●●● VERIFIED",
  dropped: "✕ DROPPED",
};

// Rollout states that need no caveat at a given delivery stage; anything else
// is printed so the bare meter can't mislead (e.g. UAT but dormant).
const UNREMARKABLE = {
  backlog: ["not-deployed"],
  ready: ["not-deployed"],
  "in-progress": ["not-deployed", "local-only"],
  uat: ["test-deployment", "live"],
  verified: ["test-deployment", "live"],
  dropped: ROLLOUT,
};
const ROLLOUT_NOTE = {
  "not-deployed": "not deployed",
  "local-only": "local only",
  "test-deployment": "deployed (test)",
  dormant: "dormant",
  live: "live",
};

function statusText(n) {
  const notes = [];
  if (n.rollout && !UNREMARKABLE[n.delivery].includes(n.rollout))
    notes.push(ROLLOUT_NOTE[n.rollout]);
  if (n.qualifier) notes.push(n.qualifier);
  return `${METER[n.delivery]}${notes.length ? ` — ${notes.join("; ")}` : ""}`;
}

function wrap(text, firstPrefix, contPrefix, width = 80) {
  const words = text.split(" ");
  const out = [];
  let line = firstPrefix;
  let empty = true;
  for (const word of words) {
    if (!empty && line.length + 1 + word.length > width) {
      out.push(line);
      line = contPrefix;
      empty = true;
    }
    line += (empty ? "" : " ") + word;
    empty = false;
  }
  out.push(line);
  return out;
}

/** Renders the roadmap trees (both areas) from a validated registry. */
export function renderRoadmap(nodes) {
  const children = new Map();
  const childrenOf = (id) => children.get(id) ?? [];
  for (const n of nodes) {
    if (!children.has(n.parent)) children.set(n.parent, []);
    children.get(n.parent).push(n);
  }
  for (const list of children.values())
    list.sort((a, b) => a.order - b.order || a.label.localeCompare(b.label));

  const lines = [];
  function renderNode(n, branch, cont) {
    const text =
      n.kind === "group"
        ? `${n.label}${n.qualifier ? ` — ${n.qualifier}` : ""}`
        : `${n.label} ${statusText(n)}`;
    lines.push(...wrap(text, branch, cont + "    "));
    const kids = childrenOf(n.id);
    kids.forEach((kid, k) => {
      const last = k === kids.length - 1;
      renderNode(
        kid,
        cont + (last ? "└── " : "├── "),
        cont + (last ? "    " : "│   "),
      );
    });
  }

  const sections = {
    frontend: "### Frontend (storefront)",
    backend: "### Backend (admin + data)",
  };
  const out = [];
  for (const area of AREAS) {
    out.push(sections[area], "", "```text");
    const roots = childrenOf(area);
    roots.forEach((root, r) => {
      lines.length = 0;
      renderNode(root, "", "");
      out.push(...lines);
      if (r < roots.length - 1) out.push("");
    });
    out.push("```", "");
  }
  return out.join("\n").trimEnd();
}

/** Returns README text with the generated block replaced; throws when markers are missing. */
export function spliceReadme(readme, block) {
  const begin = readme.indexOf(BEGIN_MARK);
  const end = readme.indexOf(END_MARK);
  if (begin === -1 || end === -1 || end < begin)
    throw new Error("docs/features/README.md: roadmap markers not found");
  return (
    readme.slice(0, begin + BEGIN_MARK.length) +
    "\n\n" +
    block +
    "\n\n" +
    readme.slice(end)
  );
}

/** Regenerates the README roadmap block. Returns true when the file changed. */
export function generate({ write = true } = {}) {
  const readme = readFileSync(README, "utf8");
  const next = spliceReadme(readme, renderRoadmap(loadRegistry()));
  const changed = next !== readme;
  if (changed && write) writeFileSync(README, next);
  return changed;
}
